/**
 * Adjust only site-root-relative URLs in generated static output.
 * The canonical renderer and saved JSON always use paths rooted at /.
 * GitHub Pages serves a project from /<repo>/ instead of a domain root.
 */
export function normalizeBasePath(input = '/') {
  if (typeof input !== 'string' || !/^\/(?:[a-zA-Z0-9_.~-]+\/)*$/.test(input) || input.includes('..')) {
    throw new Error('TA_BASE_PATH must be / or a safe slash-terminated absolute path, e.g. /my-repo/');
  }
  return input;
}

export function prefixSitePaths(source, basePath = '/') {
  const base = normalizeBasePath(basePath);
  if (base === '/') return source;
  // Escaped HTML is generated by our renderer; we rewrite only double-quoted,
  // local absolute URL attributes, never URLs inside authoring data or text.
  return source.replace(/\b(href|src|poster|action)="\/(?!\/)([^"]*)"/g, (match, attr, remainder) => {
    const original = '/' + remainder;
    if (original.startsWith(base)) return match;
    return `${attr}="${base}${remainder}"`;
  });
}

export function prefixCssPaths(css, basePath = '/') {
  const base = normalizeBasePath(basePath);
  if (base === '/') return css;
  return css.replace(/url\(\s*(["']?)\/(?!\/)([^)'"\s]+)\1\s*\)/gi, (match, quote, remainder) => {
    if (('/' + remainder).startsWith(base)) return match;
    return `url(${quote}${base}${remainder}${quote})`;
  });
}